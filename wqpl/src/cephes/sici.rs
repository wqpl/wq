/// Compute sine integral Si(x) and cosine integral Ci(x).
///
/// Si(x) = ∫₀ˣ sin(t)/t dt
/// Ci(x) = γ + ln(x) + ∫₀ˣ (cos(t)-1)/t dt
pub fn sici(x: f64) -> (f64, f64) {
    let sign = if x < 0.0 { -1.0 } else { 1.0 };
    let ax = x.abs();

    if ax == 0.0 {
        return (0.0, f64::NEG_INFINITY);
    }

    if ax > 1.0e9 {
        let si = std::f64::consts::FRAC_PI_2 - ax.cos() / ax;
        let ci = ax.sin() / ax;
        return (sign * si, ci);
    }

    if ax > 4.0 {
        let s = ax.sin();
        let c = ax.cos();
        let z = 1.0 / (ax * ax);
        let (f, g) = if ax < 8.0 {
            let f = polevl(z, FN4) / (ax * p1evl(z, FD4));
            let g = z * polevl(z, GN4) / p1evl(z, GD4);
            (f, g)
        } else {
            let f = polevl(z, FN8) / (ax * p1evl(z, FD8));
            let g = z * polevl(z, GN8) / p1evl(z, GD8);
            (f, g)
        };
        let si = std::f64::consts::FRAC_PI_2 - f * c - g * s;
        let ci = f * s - g * c;
        return (sign * si, ci);
    }

    let z = ax * ax;
    let s = ax * polevl(z, SN) / polevl(z, SD);
    let c = z * polevl(z, CN) / polevl(z, CD);
    (sign * s, EUL + ax.ln() + c)
}

/// Sine integral Si(x).
pub fn si(x: f64) -> f64 {
    sici(x).0
}

/// Cosine integral Ci(x).
pub fn ci(x: f64) -> f64 {
    sici(x).1
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn si_known_values() {
        assert!(si(0.0).abs() < 1e-15);
        assert!((si(1.0) - 0.9460830703671830).abs() < 1e-14);
        assert!((si(2.0) - 1.6054129768026948).abs() < 1e-14);
        assert!((si(-1.0) + 0.9460830703671830).abs() < 1e-14);
    }

    #[test]
    fn ci_known_values() {
        assert!(ci(0.0).is_infinite() && ci(0.0).is_sign_negative());
        assert!((ci(1.0) - 0.3374039229009681).abs() < 1e-14);
        assert!((ci(2.0) - 0.4229808287748650).abs() < 1e-14);
    }
}
