/// Exponential integral Ei(x) for real x > 0.
/// Returns NaN for x <= 0.
pub fn ei(x: f64) -> f64 {
    if x <= 0.0 {
        return f64::NAN;
    }
    let w: f64;
    let f: f64;
    if x < 2.0 {
        f = polevl(x, EI_A) / p1evl(x, EI_B);
        EUL + x.ln() + x * f
    } else if x < 4.0 {
        w = 1.0 / x;
        f = polevl(w, EI_A6) / p1evl(w, EI_B6);
        x.exp() * w * (1.0 + w * f)
    } else if x < 8.0 {
        w = 1.0 / x;
        f = polevl(w, EI_A5) / p1evl(w, EI_B5);
        x.exp() * w * (1.0 + w * f)
    } else if x < 16.0 {
        w = 1.0 / x;
        f = polevl(w, EI_A2) / p1evl(w, EI_B2);
        x.exp() * w * (1.0 + w * f)
    } else if x < 32.0 {
        w = 1.0 / x;
        f = polevl(w, EI_A4) / p1evl(w, EI_B4);
        x.exp() * w * (1.0 + w * f)
    } else if x < 64.0 {
        w = 1.0 / x;
        f = polevl(w, EI_A7) / p1evl(w, EI_B7);
        x.exp() * w * (1.0 + w * f)
    } else {
        w = 1.0 / x;
        f = polevl(w, EI_A3) / p1evl(w, EI_B3);
        x.exp() * w * (1.0 + w * f)
    }
}

